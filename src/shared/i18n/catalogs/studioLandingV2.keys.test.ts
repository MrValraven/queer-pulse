const NAMESPACES = ["studio", "notifications", "admin", "subprofiles"] as const;

const KEYS_BY_NAMESPACE: Record<(typeof NAMESPACES)[number], string[]> = {
  studio: [...NEW_STUDIO_KEYS, ...REWRITTEN_STUDIO_KEYS],
  notifications: NEW_NOTIFICATIONS_KEYS,
  admin: NEW_ADMIN_KEYS,
  subprofiles: NEW_SUBPROFILES_KEYS,
};

const tokensOf = (value: string) =>
  [...value.matchAll(/\{(\w+)\}/g)].map((match) => match[1]).sort();

describe("Studio landing v2 catalog keys", () => {
  it.each(NAMESPACES)(
    "%s: every key exists in en and pt with the same tokens",
    async (namespace) => {
      const [en, pt] = await Promise.all([
        loadNamespace("en", namespace),
        loadNamespace("pt", namespace),
      ]);
      for (const key of KEYS_BY_NAMESPACE[namespace]) {
        expect(en[key], `en ${namespace}:${key}`).toEqual(expect.any(String));
        expect(pt[key], `pt ${namespace}:${key}`).toEqual(expect.any(String));
        expect(tokensOf(pt[key] ?? ""), key).toEqual(tokensOf(en[key] ?? ""));
      }
    },
  );
  it.each(NAMESPACES)(
    "%s: no dashes, antithesis, gathering or room",
    async (namespace) => {
      for (const language of ["en", "pt"] as const) {
        const catalog = await loadNamespace(language, namespace);
        for (const key of KEYS_BY_NAMESPACE[namespace]) {
          const value = catalog[key] ?? "";
          expect(value, key).not.toMatch(/[\u2013\u2014]/);
          expect(value, key).not.toMatch(
            /, not |rather than|instead of|not just|, never /i,
          );
          expect(value, key).not.toMatch(
            /\bgathering\b|\broom\b|a real person/i,
          );
        }
      }
    },
  );
  it("names the Spotify fact with its figure and keeps money claims out of the Studio line", async () => {
    const en = await loadNamespace("en", "studio");
    expect(en["landing.forArtists.spotify.fact"]).toContain("1,000 streams");
    expect(en["landing.forArtists.spotify.studio"]).not.toMatch(
      /€|\d+\s?%|we take nothing/i,
    );
  });
  it("promises a notification and never an email", async () => {
    for (const language of ["en", "pt"] as const) {
      const catalog = await loadNamespace(language, "studio");
      for (const key of [
        "landing.cta.onList.body",
        "landing.next.list.body",
        "landing.faq.getIn.answer",
      ])
        expect(catalog[key] ?? "", key).not.toMatch(/e-?mail/i);
    }
  });
  it("maps each landing reason code to its own errors.reason key in en and pt", async () => {
    const [en, pt] = await Promise.all([
      loadNamespace("en", "studio"),
      loadNamespace("pt", "studio"),
    ]);
    expect(LANDING_ERROR_CODES).toHaveLength(23);
    for (const code of LANDING_ERROR_CODES) {
      expect(STUDIO_ERROR_MESSAGE_KEY[code]).toBe(
        `studio:errors.reason.${code}`,
      );
      const key = `errors.reason.${code}`;
      expect(en[key], `en ${key}`).toEqual(expect.any(String));
      expect(pt[key], `pt ${key}`).toEqual(expect.any(String));
    }
  });
  it("uses gender-neutral people nouns in PT", async () => {
    const pt = await loadNamespace("pt", "studio");
    for (const key of KEYS_BY_NAMESPACE.studio)
      expect(pt[key] ?? "", key).not.toMatch(/seguidor|apoiador|utilizador/i);
  });
});
