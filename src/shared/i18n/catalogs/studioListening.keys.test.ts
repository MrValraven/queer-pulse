const REWRITTEN_KEYS = [
  "accessibility.shortcuts.dek",
  "upload.side.files.list.loudnessTarget.value",
] as const;

const tokensOf = (value: string) =>
  [...value.matchAll(/\{(\w+)\}/g)].map((match) => match[1]).sort();

describe("Studio Listening catalog keys", () => {
  it("exist in both languages with the same tokens", () => {
    for (const key of [...LISTENING_KEYS, ...REWRITTEN_KEYS]) {
      expect(en[key], `en ${key}`).toEqual(expect.any(String));
      expect(pt[key], `pt ${key}`).toEqual(expect.any(String));
      expect(tokensOf(pt[key] ?? ""), key).toEqual(tokensOf(en[key] ?? ""));
    }
  });

  it("carry no dashes and no antithesis", () => {
    for (const key of [...LISTENING_KEYS, ...REWRITTEN_KEYS])
      for (const value of [en[key] ?? "", pt[key] ?? ""]) {
        expect(value, key).not.toMatch(/[\u2013\u2014]/);
        expect(value, key).not.toMatch(
          /, not |rather than|instead of|not just|, never /,
        );
      }
  });

  it("keep contract D's shortcut keys", () => {
    for (const action of [
      "playPause",
      "seekBack",
      "seekForward",
      "previousTrack",
      "nextTrack",
      "volumeUp",
      "volumeDown",
      "mute",
      "shuffle",
      "repeat",
      "lyrics",
      "queue",
      "help",
    ])
      expect(en[`shortcuts.${action}`]).toEqual(expect.any(String));
    expect(en["chapters.error.outOfRange"]).toEqual(expect.any(String));
  });
});
